/// Maximum aggregate token-piece bytes retained by a prepared tokenizer table.
pub const MAX_STRUCTURED_TOKENIZER_TABLE_BYTES: usize = 64 * 1024 * 1024;
/// Maximum canonical artifact or validation-report bytes hashed per attempt.
pub const MAX_STRUCTURED_VALIDATION_EVIDENCE_BYTES: usize = 1024 * 1024;

const RETAINED_ERROR_BYTES: usize = 512;

/// One exact model-tokenizer candidate presented to byte feedback.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ByteFeedbackCandidate<'a> {
    /// Exact tokenizer ID.
    pub token: TokenId,
    /// Exact token-piece bytes, which need not be UTF-8.
    pub piece: &'a [u8],
    /// Whether the loaded vocabulary classifies the token as end-of-generation.
    pub end_of_generation: bool,
}

/// Bounded implementation error from exact-byte feedback.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ByteFeedbackError {
    message: String,
}

impl ByteFeedbackError {
    /// Creates an implementation error. The native adapter bounds retained
    /// text when crossing the callback boundary.
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }
}

impl fmt::Display for ByteFeedbackError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.message)
    }
}

impl std::error::Error for ByteFeedbackError {}

/// Stateful exact-byte candidate feedback for one structured attempt.
pub trait ByteFeedback {
    /// Resets implementation state at the exact common causal boundary.
    ///
    /// # Errors
    ///
    /// Returns an implementation-defined reset failure.
    fn reset(&mut self, causal_tokens: &[TokenId]) -> Result<(), ByteFeedbackError>;

    /// Returns whether one exact token piece may extend current symbolic state.
    ///
    /// # Errors
    ///
    /// Returns an implementation-defined decision failure.
    fn allows(&self, candidate: ByteFeedbackCandidate<'_>) -> Result<bool, ByteFeedbackError>;

    /// Admits one selected non-EOG token piece after native causal admission.
    ///
    /// # Errors
    ///
    /// Returns an implementation-defined state-transition failure.
    fn accept(&mut self, candidate: ByteFeedbackCandidate<'_>) -> Result<(), ByteFeedbackError>;

    /// Returns an exact identity for current implementation-local state.
    ///
    /// # Errors
    ///
    /// Returns an implementation-defined state-identity failure.
    fn state_digest(&self) -> Result<Digest, ByteFeedbackError>;

    /// Returns whether current admitted bytes form a complete symbolic
    /// artifact.
    ///
    /// # Errors
    ///
    /// Returns an implementation-defined completion failure.
    fn complete(&self) -> Result<bool, ByteFeedbackError>;
}

